def _sbox_round(name, table, bits, nibbles=1, add_permutation=None):
    """A register bank feeding ``nibbles`` copies of an S-box, then back."""
    builder = Builder(name)
    builder.port("input", "clk")
    builder.port("input", "rst_n")
    width = bits * nibbles
    builder.port("output", "dout", width)
    builder.wire("state", width)
    builder.wire("sub", width)
    for nibble in range(nibbles):
        base = nibble * bits
        inputs = ["state[{}]".format(base + index) for index in range(bits)]
        for position in range(bits):
            builder.function(
                "sb{}_{}".format(nibble, position),
                "sub[{}]".format(base + position),
                inputs,
                lambda values, position=position: (
                    table[sum(bit << index for index, bit in enumerate(values))] >> position
                )
                & 1,
            )
    for index in range(width):
        source = index if add_permutation is None else add_permutation[index]
        builder.register(
            "state_{}".format(index),
            "sub[{}]".format(source),
            "state[{}]".format(index),
            clear="rst_n",
        )
        builder.assign("dout[{}]".format(index), "state[{}]".format(index))
    return builder


def _shift_chain(name, length, taps=None, nonlinear=False, galois_taps=None):
    builder = Builder(name)
    builder.port("input", "clk")
    builder.port("input", "rst_n")
    builder.port("input", "din")
    builder.port("output", "dout")
    builder.wire("state", length)

    if galois_taps is not None:
        builder.wire("fb", length)
        for index in range(length):
            if index == 0:
                builder.assign("fb[0]", "state[{}]".format(length - 1))
                data = "state[{}]".format(length - 1)
            elif index in galois_taps:
                builder.lut(
                    "gx_{}".format(index),
                    "fb[{}]".format(index),
                    ["state[{}]".format(index - 1), "state[{}]".format(length - 1)],
                    [0, 1, 1, 0],
                )
                data = "fb[{}]".format(index)
            else:
                data = "state[{}]".format(index - 1)
            builder.register(
                "state_{}".format(index), data, "state[{}]".format(index), clear="rst_n"
            )
        builder.assign("dout", "state[{}]".format(length - 1))
        return builder

    if taps is not None:
        inputs = ["state[{}]".format(tap) for tap in taps]
        if nonlinear:

            def evaluate(values):
                parity = 0
                for value in values[:-2]:
                    parity ^= value
                return parity ^ (values[-2] & values[-1])

        else:

            def evaluate(values):
                parity = 0
                for value in values:
                    parity ^= value
                return parity

        builder.wire("feedback")
        builder.function("fb", "feedback", inputs, evaluate)
        head = "feedback"
    else:
        head = "din"

    for index in range(length):
        data = head if index == 0 else "state[{}]".format(index - 1)
        builder.register(
            "state_{}".format(index), data, "state[{}]".format(index), clear="rst_n"
        )
    builder.assign("dout", "state[{}]".format(length - 1))
    return builder


def _loadable_lfsr(name, length=16, taps=(3, 12, 14, 15)):
    """The Fibonacci LFSR above, behind a parallel ``load ? seed : shift``.

    Every stage's next state is a multiplexer, so the plain "is this register
    driven by exactly one other register" test fails on all of them at once and
    the chain is invisible until ``load`` is held at 0.  That is what a vendor
    export of any keyed generator looks like -- see
    ``examples/agilex3_walkthroughs/13_trivium_stream`` -- and it is the shape
    :func:`hal_crypto.shiftreg.mode_candidates` exists for.
    """
    builder = Builder(name)
    builder.port("input", "clk")
    builder.port("input", "rst_n")
    builder.port("input", "load")
    builder.port("input", "seed", length)
    builder.port("output", "dout")
    builder.wire("state", length)
    builder.wire("nxt", length)
    builder.wire("feedback")

    def parity(values):
        result = 0
        for value in values:
            result ^= value
        return result

    builder.function(
        "fb", "feedback", ["state[{}]".format(tap) for tap in taps], parity
    )
    for index in range(length):
        shifted = "feedback" if index == 0 else "state[{}]".format(index - 1)
        data = "nxt[{}]".format(index)
        builder.lut(
            "mux_{}".format(index),
            data,
            ["load", "seed[{}]".format(index), shifted],
            # address bit 0 = load, 1 = seed, 2 = shifted
            [0, 0, 0, 1, 1, 0, 1, 1],
        )
        builder.register(
            "state_{}".format(index), data, "state[{}]".format(index), clear="rst_n"
        )
    builder.assign("dout", "state[{}]".format(length - 1))
    return builder


def _coupled_nlfsr(name, lengths=(8, 10)):
    """Two shift registers, each closed through the *other* one.

    Neither chain's feedback is a function of its own stages alone, so neither
    has a feedback polynomial or a period; together they are one 18-bit
    nonlinear generator.  This is the Trivium/Grain shape at toy size, and it is
    the minimum case for the ``coupled`` reporting in
    :func:`hal_crypto.shiftreg.find_shift_structures`.
    """
    builder = Builder(name)
    builder.port("input", "clk")
    builder.port("input", "rst_n")
    builder.port("output", "dout")
    first, second = lengths
    builder.wire("a", first)
    builder.wire("b", second)
    builder.wire("head_a")
    builder.wire("head_b")

    def feedback(values):
        # own tap ^ foreign tap ^ (two adjacent foreign stages ANDed)
        return values[0] ^ values[1] ^ (values[2] & values[3])

    builder.function(
        "fa",
        "head_a",
        [
            "a[{}]".format(first - 3),
            "b[{}]".format(second - 1),
            "b[{}]".format(second - 3),
            "b[{}]".format(second - 2),
        ],
        feedback,
    )
    builder.function(
        "fb",
        "head_b",
        [
            "b[{}]".format(second - 4),
            "a[{}]".format(first - 1),
            "a[{}]".format(first - 3),
            "a[{}]".format(first - 2),
        ],
        feedback,
    )
    for index in range(first):
        data = "head_a" if index == 0 else "a[{}]".format(index - 1)
        builder.register("a_{}".format(index), data, "a[{}]".format(index), clear="rst_n")
    for index in range(second):
        data = "head_b" if index == 0 else "b[{}]".format(index - 1)
        builder.register("b_{}".format(index), data, "b[{}]".format(index), clear="rst_n")
    builder.assign("dout", "a[{}]".format(first - 1))
    return builder


def _arx_round(name, width=8, rotation=3):
    """One ARX round: add two registered words, rotate, XOR, register back."""
    builder = Builder(name)
    builder.port("input", "clk")
    builder.port("input", "rst_n")
    builder.port("input", "load", width)
    builder.port("output", "dout", width)
    builder.wire("x", width)
    builder.wire("y", width)
    builder.wire("sum", width)
    builder.wire("rot", width)
    builder.wire("xored", width)

    builder.adder(
        "add",
        ["x[{}]".format(index) for index in range(width)],
        ["y[{}]".format(index) for index in range(width)],
        ["sum[{}]".format(index) for index in range(width)],
    )
    for index in range(width):
        builder.assign("rot[{}]".format(index), "y[{}]".format((index - rotation) % width))
        builder.lut(
            "xor_{}".format(index),
            "xored[{}]".format(index),
            ["sum[{}]".format(index), "rot[{}]".format(index)],
            [0, 1, 1, 0],
        )
        builder.register(
            "x_{}".format(index), "sum[{}]".format(index), "x[{}]".format(index),
            clear="rst_n",
        )
        builder.register(
            "y_{}".format(index), "xored[{}]".format(index), "y[{}]".format(index),
            clear="rst_n",
        )
        builder.assign("dout[{}]".format(index), "x[{}]".format(index))
    return builder


def _counter(name, width=8):
    """An adder-only accumulator: the ARX negative control.

    The second operand is a port rather than the constant 1, so the carry chain
    really is a two-operand adder and the fixture tests "an adder on its own is
    not ARX" instead of "there is no adder here".
    """
    builder = Builder(name)
    builder.port("input", "clk")
    builder.port("input", "rst_n")
    builder.port("input", "step", width)
    builder.port("output", "dout", width)
    builder.wire("count", width)
    builder.wire("sum", width)
    builder.adder(
        "add",
        ["count[{}]".format(index) for index in range(width)],
        ["step[{}]".format(index) for index in range(width)],
        ["sum[{}]".format(index) for index in range(width)],
    )
    for index in range(width):
        builder.register(
            "count_{}".format(index), "sum[{}]".format(index), "count[{}]".format(index),
            clear="rst_n",
        )
        builder.assign("dout[{}]".format(index), "count[{}]".format(index))
    return builder


def _butterfly(name, width=4):
    """A single NTT-style butterfly: ``a+b`` and ``a-b`` over the same operands."""
    builder = Builder(name)
    builder.port("input", "clk")
    builder.port("input", "rst_n")
    builder.port("output", "up", width + 1)
    builder.port("output", "down", width + 1)
    builder.wire("a", width)
    builder.wire("b", width)
    builder.wire("nb", width)
    builder.wire("sum", width)
    builder.wire("diff", width)
    builder.wire("sum_r", width)
    builder.wire("diff_r", width)

    for index in range(width):
        builder.lut("inv_{}".format(index), "nb[{}]".format(index),
                    ["b[{}]".format(index)], [1, 0])
    builder.adder(
        "add",
        ["a[{}]".format(index) for index in range(width)],
        ["b[{}]".format(index) for index in range(width)],
        ["sum[{}]".format(index) for index in range(width)],
    )
    builder.adder(
        "sub",
        ["a[{}]".format(index) for index in range(width)],
        ["nb[{}]".format(index) for index in range(width)],
        ["diff[{}]".format(index) for index in range(width)],
        carry_in="vcc",
    )
    for index in range(width):
        builder.register("a_{}".format(index), "sum[{}]".format(index),
                         "a[{}]".format(index), clear="rst_n")
        builder.register("b_{}".format(index), "diff[{}]".format(index),
                         "b[{}]".format(index), clear="rst_n")
        builder.register("sr_{}".format(index), "sum[{}]".format(index),
                         "sum_r[{}]".format(index), clear="rst_n")
        builder.register("dr_{}".format(index), "diff[{}]".format(index),
                         "diff_r[{}]".format(index), clear="rst_n")
        builder.assign("up[{}]".format(index), "sum_r[{}]".format(index))
        builder.assign("down[{}]".format(index), "diff_r[{}]".format(index))
    builder.assign("up[{}]".format(width), "gnd")
    builder.assign("down[{}]".format(width), "gnd")
    return builder


def _ntt_stage(name, bits=13, modulus=3329):
    """A butterfly whose sum is reduced modulo *q* by a conditional subtract.

    ``sum - q`` is built as ``sum + (2**bits - q)``, which is how a hardware
    reduction is written and which is why the modulus has to be read back out
    of the constant as ``2**w - k``.
    """
    builder = Builder(name)
    builder.port("input", "clk")
    builder.port("input", "rst_n")
    builder.port("output", "dout", bits)
    for vector in ("a", "b", "nb", "sum", "diff", "red", "out"):
        builder.wire(vector, bits)
    builder.wire("ge")

    complement = (1 << bits) - modulus
    for index in range(bits):
        builder.lut("inv_{}".format(index), "nb[{}]".format(index),
                    ["b[{}]".format(index)], [1, 0])
    builder.adder(
        "add",
        ["a[{}]".format(index) for index in range(bits)],
        ["b[{}]".format(index) for index in range(bits)],
        ["sum[{}]".format(index) for index in range(bits)],
    )
    builder.adder(
        "sub",
        ["a[{}]".format(index) for index in range(bits)],
        ["nb[{}]".format(index) for index in range(bits)],
        ["diff[{}]".format(index) for index in range(bits)],
        carry_in="vcc",
    )
    builder.adder(
        "mod",
        ["sum[{}]".format(index) for index in range(bits)],
        ["vcc" if (complement >> index) & 1 else "gnd" for index in range(bits)],
        ["red[{}]".format(index) for index in range(bits)],
        carry_out="ge",
    )
    for index in range(bits):
        builder.lut(
            "mux_{}".format(index),
            "out[{}]".format(index),
            ["sum[{}]".format(index), "red[{}]".format(index), "ge"],
            [0, 1, 0, 1, 0, 0, 1, 1],
        )
        builder.register("a_{}".format(index), "out[{}]".format(index),
                         "a[{}]".format(index), clear="rst_n")
        builder.register("b_{}".format(index), "diff[{}]".format(index),
                         "b[{}]".format(index), clear="rst_n")
        builder.assign("dout[{}]".format(index), "a[{}]".format(index))
    return builder


def _rotation_layer(name, width=16, rotation=5):
    """Two register banks joined by nothing but a cyclic rewiring."""
    builder = Builder(name)
    builder.port("input", "clk")
    builder.port("input", "rst_n")
    builder.port("input", "din", width)
    builder.port("output", "dout", width)
    builder.wire("front", width)
    builder.wire("back", width)
    for index in range(width):
        builder.register("front_{}".format(index), "din[{}]".format(index),
                         "front[{}]".format(index), clear="rst_n")
        builder.register(
            "back_{}".format(index),
            "front[{}]".format((index - rotation) % width),
            "back[{}]".format(index),
            clear="rst_n",
        )
        builder.assign("dout[{}]".format(index), "back[{}]".format(index))
    return builder


