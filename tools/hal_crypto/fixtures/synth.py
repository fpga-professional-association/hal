def _mask_from_table(table):
    """A 64-bit ``lut_mask`` for a table over the first ``log2(len)`` data pins.

    The pattern is replicated over the unused address bits, the way Quartus
    writes it, so the mask is readable next to a real export.
    """
    arity = (len(table) - 1).bit_length() if len(table) > 1 else 0
    mask = 0
    for address in range(64):
        if table[address & ((1 << arity) - 1) if arity else 0]:
            mask |= 1 << address
    return mask


class Builder(object):
    """Assemble one module out of ``tennm_lcell_comb`` and ``tennm_ff`` cells."""

    def __init__(self, name):
        self.name = name
        self.ports = []          # (direction, name, width)
        self.wires = []          # (name, width)
        self._wire_names = set()
        self.body = []
        self.assigns = []
        self._counter = 0

    # -- declarations -----------------------------------------------------

    def port(self, direction, name, width=1):
        self.ports.append((direction, name, width))
        return name

    def wire(self, name, width=1):
        if name not in self._wire_names:
            self.wires.append((name, width))
            self._wire_names.add(name)
        return name

    def temp(self, stem):
        self._counter += 1
        return self.wire("{}_{}".format(stem, self._counter))

    def assign(self, target, source):
        self.assigns.append((target, source))

    # -- cells ------------------------------------------------------------

    def lut(self, name, output, inputs, table):
        """One ALM cell in normal mode computing ``table`` over ``inputs``.

        ``inputs`` are net expressions, least significant address bit first, at
        most six of them; ``table`` has ``2**len(inputs)`` entries.
        """
        if len(inputs) > 6:
            raise ValueError("an ALM cell has six data inputs, got {}".format(len(inputs)))
        if len(table) != 1 << len(inputs):
            raise ValueError(
                "a {}-input cell needs {} table entries, got {}".format(
                    len(inputs), 1 << len(inputs), len(table)
                )
            )
        pins = list(inputs) + ["gnd"] * (6 - len(inputs))
        connections = [
            ".{}({})".format(pin, pins[position])
            for position, pin in enumerate(primitives.LCELL_DATA_PINS)
        ]
        connections += [".datag(gnd)", ".datah(gnd)", ".cin(gnd)", ".sharein(gnd)"]
        connections += [
            ".combout({})".format(output),
            ".sumout()",
            ".cout()",
            ".shareout()",
        ]
        self._cell(name, _mask_from_table(table), connections)
        return output

    def arithmetic(self, name, operand_a, operand_b, sum_net, carry_in, carry_out):
        """One full-adder bit slice: ``sumout = a ^ b ^ cin`` on the carry chain."""
        low = [((index >> 2) & 1) ^ ((index >> 3) & 1) for index in range(16)]
        high = [((index >> 2) & 1) & ((index >> 3) & 1) for index in range(16)]
        mask = 0
        for index in range(16):
            if low[index]:
                mask |= 1 << index
            if high[index]:
                mask |= 1 << (16 + index)
        connections = [
            ".dataa(gnd)",
            ".datab(gnd)",
            ".datac({})".format(operand_a),
            ".datad({})".format(operand_b),
            ".datae(gnd)",
            ".dataf(gnd)",
            ".datag(gnd)",
            ".datah(gnd)",
            ".cin({})".format(carry_in),
            ".sharein(gnd)",
            ".combout()",
            ".sumout({})".format(sum_net),
            ".cout({})".format(carry_out if carry_out else ""),
            ".shareout()",
        ]
        self._cell(name, mask, connections)

    def _cell(self, name, mask, connections):
        self.body.append(
            "tennm_lcell_comb #(\n"
            '  .extended_lut ("off"),\n'
            "  .lut_mask (64'h{:016X}),\n"
            '  .shared_arith ("off"))\n'
            "{} (\n\t{});\n".format(mask, name, ",\n\t".join(connections))
        )

    def register(self, name, data, output, clock="clk", enable="vcc", clear="vcc"):
        self.body.append(
            "tennm_ff #(\n"
            '  .is_wysiwyg ("true"),\n'
            '  .power_up ("dont_care"))\n'
            "{} (\n"
            "\t.clk({}),\n"
            "\t.d({}),\n"
            "\t.asdata(vcc),\n"
            "\t.clrn({}),\n"
            "\t.aload(gnd),\n"
            "\t.sclr(gnd),\n"
            "\t.sload(gnd),\n"
            "\t.ena({}),\n"
            "\t.sclr1(gnd),\n"
            "\t.devclrn(devclrn),\n"
            "\t.devpor(devpor),\n"
            "\t.q({}));\n".format(name, clock, data, clear, enable, output)
        )

    # -- composite helpers ------------------------------------------------

    def function(self, stem, output, inputs, evaluate):
        """A function of any arity, decomposed into six-input cells.

        ``evaluate`` takes a tuple of bits (aligned with ``inputs``) and returns
        the output bit.  Inputs beyond the sixth are peeled off two at a time
        and recombined with a 4:1 multiplexer cell, which is exactly how a
        seven-or-more-input function has to be built out of ALMs.
        """
        if len(inputs) <= 6:
            table = [
                evaluate(tuple((index >> position) & 1 for position in range(len(inputs))))
                for index in range(1 << len(inputs))
            ]
            return self.lut(stem, output, inputs, table)

        selects = inputs[-2:]
        rest = inputs[:-2]
        branches = []
        for choice in range(4):
            branch = self.wire("{}_b{}".format(output, choice))
            self.function(
                "{}_b{}".format(stem, choice),
                branch,
                rest,
                lambda bits, choice=choice: evaluate(
                    tuple(bits) + (choice & 1, (choice >> 1) & 1)
                ),
            )
            branches.append(branch)
        table = []
        for index in range(64):
            selector = (index >> 4) & 3
            table.append((index >> selector) & 1)
        return self.lut(stem + "_mux", output, branches + list(selects), table)

    def adder(self, stem, operands_a, operands_b, sums, carry_in="gnd", carry_out=None):
        """A ripple-carry chain over the two operand bit lists."""
        carry = carry_in
        for index, (a, b) in enumerate(zip(operands_a, operands_b)):
            last = index == len(operands_a) - 1
            following = (carry_out or "") if last else self.wire(
                "{}_c{}".format(stem, index)
            )
            self.arithmetic(
                "{}_{}".format(stem, index), a, b, sums[index], carry, following
            )
            carry = following
        return carry

    # -- output -----------------------------------------------------------

    def dumps(self):
        lines = [HEADER, "module {} (".format(self.name)]
        lines.append(
            ",\n".join("\t" + name for _, name, _ in self.ports) + ");"
        )
        for direction, name, width in self.ports:
            span = "" if width == 1 else "\t[{}:0]".format(width - 1)
            lines.append("{} {} {};".format(direction, span, name))
        lines.append("")
        lines.append("wire gnd;")
        lines.append("wire vcc;")
        lines.append("assign gnd = 1'b0;")
        lines.append("assign vcc = 1'b1;")
        lines.append("tri1 devclrn;")
        lines.append("tri1 devpor;")
        for name, width in self.wires:
            span = "" if width == 1 else " [{}:0]".format(width - 1)
            lines.append("wire{} {};".format(span, name))
        lines.append("")
        lines.extend(self.body)
        for target, source in self.assigns:
            lines.append("assign {} = {};".format(target, source))
        lines.append("")
        lines.append("endmodule")
        return "\n".join(lines) + "\n"


