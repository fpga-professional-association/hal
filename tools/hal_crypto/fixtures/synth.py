#: The manifest that ships next to the generated netlists.
MANIFEST_NAME = "MANIFEST.json"


def build_all():
    """``{name: verilog text}`` for every fixture."""
    return {name: entry["build"]().dumps() for name, entry in sorted(FIXTURES.items())}


def manifest(texts=None):
    """The manifest contents, derived from the fixture table and the texts."""
    texts = texts or build_all()
    return {
        "generator": "tools/hal_crypto/fixtures/synth.py",
        "kind": "synthesized shapes, not vendor exports",
        "family": "Agilex 3",
        "device": "A3CW135BM16AE6S",
        "provenance": (
            "Assembled from the tennm_lcell_comb and tennm_ff semantics in "
            "hal_agilex.primitives, which were validated against real Quartus "
            "exports in tools/hal_agilex/fixtures. Nothing here came out of "
            "Quartus, so nothing here is evidence about vendor primitive "
            "behaviour -- only about the hal_crypto recognizers."
        ),
        "regenerate": ["python tools/hal_crypto fixtures --write"],
        "verify": ["python tools/hal_crypto fixtures --check"],
        "files": {
            "{}.vo".format(name): {
                "description": FIXTURES[name]["description"],
                "role": FIXTURES[name]["role"],
                "expected_family": FIXTURES[name]["family"],
                "expected_style": FIXTURES[name]["style"],
                "sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
                "size_bytes": len(text.encode("utf-8")),
            }
            for name, text in sorted(texts.items())
        },
    }


def _manifest_text(texts=None):
    return json.dumps(manifest(texts), indent=2, sort_keys=True) + "\n"


def _path(directory, name):
    return os.path.join(directory, "{}.vo".format(name))


def _expected(directory):
    texts = build_all()
    expected = {_path(directory, name): text for name, text in texts.items()}
    expected[os.path.join(directory, MANIFEST_NAME)] = _manifest_text(texts)
    return expected


def write_all(directory):
    written = []
    for path, text in sorted(_expected(directory).items()):
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        written.append(path)
    return written


def check_all(directory):
    """Paths whose committed content differs from what this module generates."""
    stale = []
    for path, text in sorted(_expected(directory).items()):
        if not os.path.isfile(path):
            stale.append(path)
            continue
        with open(path, "r", encoding="utf-8") as handle:
            if handle.read() != text:
                stale.append(path)
    return stale
