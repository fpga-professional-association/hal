"""Emit small Agilex-shaped ``.vo`` netlists for the recognition tests.

These are **synthesized shapes, not vendor exports**.  The real Quartus
exports in ``tools/hal_agilex/fixtures`` are what establishes that the
``tennm_lcell_comb`` / ``tennm_ff`` semantics in ``hal_agilex.primitives`` are
correct; this module only assembles cells *using* those same semantics, so it
can build the structures a crypto core is made of -- an S-box, a feedback shift
register, a rotation, a butterfly -- without a Quartus licence.

Two consequences follow and both are deliberate:

* a fixture built here proves something about the *recognizer*, never about the
  vendor's primitive behaviour, and the ``GROUND_TRUTH.md`` next to the
  generated files says so;
* the emitted text goes through the same ``hal_agilex.vo_netlist`` reader as a
  real export, so a fixture that the reader would refuse cannot be written
  here and quietly bypass it.

The committed ``.vo`` files are regenerated by ``python tools/hal_crypto
fixtures --check`` (or ``--write``), which is what keeps them from drifting
away from this generator.
"""

