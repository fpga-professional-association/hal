def _control_bijection():
    """A fixed 4-bit bijection that is in no published library.

    The S-box negative control.  It is hard-coded rather than drawn at random
    so it cannot drift, and ``test_hal_crypto`` checks it against every library
    entry at every match tier -- if a future library addition collides with it,
    that test fails and the control gets replaced deliberately.
    """
    return (0x0, 0x3, 0x5, 0x8, 0xB, 0xE, 0x1, 0x6, 0xD, 0x2, 0xF, 0x4, 0x9, 0xC, 0x7, 0xA)


