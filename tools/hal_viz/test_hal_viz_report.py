def _method(kind="formal", bounded=False, name="test method"):
    return {"name": name, "kind": kind, "bounded": bounded}


def _scope(gates=None, description="the region this finding is about"):
    scope = {"artifact_ids": ["uart"], "description": description}
    if gates:
        scope["gates"] = gates
    return scope


def _gate(gate_id=1, name="state_reg_0", gate_type="FFR"):
    return {"artifact_id": "uart", "id": gate_id, "name": name, "type": gate_type}


def finding_for(status, **overrides):
    """A minimal, schema-valid finding for each of the nine statuses."""
    base = {
        "id": "test/{}".format(status.replace("_", "-")),
        "title": "finding with status {}".format(status),
        "summary": "summary of the {} finding".format(status),
        "status": status,
        "method": _method(),
        "scope": _scope([_gate()]),
    }
    if status == "proven_under_assumptions":
        base["bounds"] = {"unbounded": True}
        base["assumptions"] = [
            {
                "id": "clock.single",
                "description": "the design has a single clock domain",
                "kind": "structural",
                "discharged": False,
            }
        ]
    elif status == "proven_bounded":
        base["bounds"] = {"unbounded": False, "cycle_bound": 8}
        base["method"] = _method("bounded_formal", True)
        base["assumptions"] = []
    elif status == "counterexample":
        base["bounds"] = {"unbounded": True}
        base["counterexample"] = {
            "description": "the outputs differ",
            "witness": [{"signal": "rx_data", "value": "0x41"}],
        }
    elif status == "bounded_counterexample":
        base["bounds"] = {"unbounded": False, "cycle_bound": 12}
        base["method"] = _method("bounded_formal", True)
        base["counterexample"] = {
            "description": "the outputs differ within 5 cycles",
            "cycle_bound": 5,
            "witness": [{"signal": "rx_data", "cycle": 5, "value": "0x41"}],
        }
    elif status == "heuristic":
        base["method"] = _method("heuristic", False, "dataflow analysis (DANA)")
        base["confidence"] = 0.8
    elif status == "timeout":
        base["limits"] = {"timeout_s": 60, "hit": True}
    elif status == "error":
        base["error"] = {"kind": "plugin_error", "message": "the plugin returned None"}
    elif status == "unsupported":
        base["unsupported"] = {
            "kind": "primitive",
            "reason": "block RAM is not modelled",
            "primitives": [
                {
                    "gate_type": "RAMB18E1",
                    "reason": "not a flip-flop",
                    "count": 4,
                    "example_gates": [_gate(1701, "mem_inst/bram_0", "RAMB18E1")],
                }
            ],
        }
    base.update(overrides)
    return base


def document_with(findings, notes=None):
    return {
        "schema_version": "1.0.0",
        "generated_at": "2026-01-15T09:30:00Z",
        "producer": {"name": "test_hal_viz_report", "version": "1.0.0"},
        "artifacts": [dict(_ARTIFACT)],
        "analysis": {
            "plugin": {"name": "test_plugin", "version": "0.1.0"},
            "entry_point": "test.analyze",
        },
        "findings": list(findings),
        "notes": list(notes or []),
    }


class ReportTestCase(unittest.TestCase):
    """Base class with a temporary directory and a one-call render helper."""

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.tmp = self._tmp.name
        self.addCleanup(self._tmp.cleanup)

    def write_document(self, document, name="findings.json"):
        path = os.path.join(self.tmp, name)
        with open(path, "w", encoding="utf-8") as handle:
            json.dump(document, handle)
        return path

    def render(self, document, name="findings.json", artifacts=(), **options):
        """Write ``document``, render it, and return the HTML page."""
        path = self.write_document(document, name)
        loaded = report.load_documents([path])
        opts = report.ReportOptions(
            report_path=os.path.join(self.tmp, "report.html"), **options
        )
        page, builder = report.build_report(loaded, opts, artifacts)
        self.builder = builder
        self.loaded = loaded
        return page


