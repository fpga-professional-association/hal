class TestEscaping(ReportTestCase):
    def test_text_escapes_every_html_metacharacter(self):
        escaped = report.text("<a href='x' onclick=\"y\">&")
        for raw in ("<", ">", '"', "'"):
            self.assertNotIn(raw, escaped)
        self.assertIn("&lt;a", escaped)
        self.assertIn("&#x27;", escaped)
        self.assertIn("&quot;", escaped)
        self.assertIn("&amp;", escaped)

    def test_text_neutralizes_control_characters(self):
        self.assertEqual(report.text("a\x00b\x1bc"), "a�b�c")
        # tab and newline are legitimate whitespace and survive
        self.assertEqual(report.text("a\tb\nc"), "a\tb\nc")

    def test_text_handles_non_strings_and_none(self):
        self.assertEqual(report.text(None), "")
        self.assertEqual(report.text(42), "42")

    def test_hostile_netlist_names_never_reach_the_page_raw(self):
        finding = finding_for("heuristic")
        finding["scope"] = _scope([_gate(7, HOSTILE_NAME, "LUT<6>")])
        finding["title"] = HOSTILE_NAME
        finding["summary"] = HOSTILE_NAME
        page = self.render(document_with([finding]))
        self.assertNotIn("<script>alert", page)
        self.assertNotIn("</script>", page)
        self.assertIn("&lt;script&gt;alert", page)
        self.assertIn("LUT&lt;6&gt;", page)

    def test_hostile_names_in_every_reference_position(self):
        finding = finding_for("unsupported")
        finding["unsupported"]["primitives"][0]["gate_type"] = HOSTILE_NAME
        finding["unsupported"]["primitives"][0]["example_gates"] = [
            _gate(9, HOSTILE_NAME, HOSTILE_NAME)
        ]
        finding["scope"]["nets"] = [
            {"artifact_id": "uart", "id": 3, "name": HOSTILE_NAME, "role": "clock"}
        ]
        finding["scope"]["modules"] = [
            {"artifact_id": "uart", "id": 1, "name": HOSTILE_NAME}
        ]
        finding["scope"]["gate_types"] = [HOSTILE_NAME]
        document = document_with([finding], notes=[HOSTILE_NAME])
        document["artifacts"][0]["design_name"] = HOSTILE_NAME
        document["artifacts"][0]["path"] = HOSTILE_NAME
        page = self.render(document)
        self.assertNotIn("<script>", page)
        self.assertGreater(page.count("&lt;script&gt;"), 3)

    def test_hostile_names_inside_attributes(self):
        # An unescaped name in a title="" attribute would let a quote escape it.
        finding = finding_for("unknown")
        finding["id"] = 'weird" onmouseover="alert(1)'
        page = self.render(document_with([finding]))
        self.assertNotIn('onmouseover="alert(1)"', page)
        self.assertIn("&quot;", page)


