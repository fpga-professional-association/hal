class TestLoading(ReportTestCase):
    def test_invalid_document_is_reported_in_the_page(self):
        document = document_with([finding_for("heuristic")])
        # a heuristic that claims to hold for every execution is exactly the
        # confusion the schema exists to prevent
        document["findings"][0]["bounds"] = {"unbounded": True}
