class TestTruncation(ReportTestCase):
    def test_long_scopes_are_truncated_visibly(self):
        finding = finding_for("heuristic")
        finding["scope"] = _scope(
            [_gate(index + 1, "state_reg_{}".format(index)) for index in range(100)]
        )
        page = self.render(document_with([finding]), max_items=5)
        self.assertIn("TRUNCATED: 95 further gate(s) not shown", page)
        self.assertIn("100 gate(s) in scope", page)
        self.assertIn("state_reg_4", page)
        self.assertNotIn("state_reg_50", page)

    def test_witness_truncation_is_visible(self):
        finding = finding_for("bounded_counterexample")
        finding["counterexample"]["witness"] = [
            {"signal": "s{}".format(index), "value": "0", "cycle": index}
            for index in range(40)
        ]
        page = self.render(document_with([finding]), max_items=3)
        self.assertIn("TRUNCATED: 37 further witness entry(s) not shown", page)

    def test_nothing_is_truncated_below_the_limit(self):
        finding = finding_for("heuristic")
        finding["scope"] = _scope([_gate(1), _gate(2, "state_reg_1")])
        page = self.render(document_with([finding]), max_items=25)
        self.assertNotIn("TRUNCATED", page)

    def test_missing_witness_is_stated(self):
        finding = finding_for("counterexample")
        finding["counterexample"] = {
            "description": "outputs differ",
            "witness_available": False,
        }
        page = self.render(document_with([finding]))
        self.assertIn("no witness is available", page)


