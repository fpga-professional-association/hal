class TestStatuses(ReportTestCase):
    ALL = (
        "proven_under_assumptions",
        "proven_bounded",
        "counterexample",
        "bounded_counterexample",
        "heuristic",
        "unknown",
        "timeout",
        "error",
        "unsupported",
    )

    def test_status_metadata_matches_the_schema_vocabulary(self):
        if findings_model is None:
            self.skipTest("hal_findings is not importable")
        self.assertEqual(set(report.STATUS_META), set(findings_model.STATUSES))
        self.assertEqual(set(self.ALL), set(findings_model.STATUSES))

    def test_fixtures_are_schema_valid(self):
        if findings_validate is None:
            self.skipTest("hal_findings is not importable")
        document = document_with([finding_for(status) for status in self.ALL])
        self.assertEqual(findings_validate.collect_errors(document), [])

    def test_all_nine_statuses_render_and_stay_distinguishable(self):
        page = self.render(document_with([finding_for(status) for status in self.ALL]))
        labels, glyphs, css = set(), set(), set()
        for status in self.ALL:
            meta = report.STATUS_META[status]
            self.assertIn(report.text(meta["label"]), page)
            self.assertIn('badge {}'.format(meta["css"]), page)
            self.assertIn("{}: {}".format(status, meta["claim"]).split(":")[0], page)
            labels.add(meta["label"])
            glyphs.add(meta["glyph"])
            css.add(meta["css"])
        # Colour alone must not carry the distinction: label, glyph and class are
        # all unique, so the nine are told apart in greyscale too.
        self.assertEqual(len(labels), 9)
        self.assertEqual(len(glyphs), 9)
        self.assertEqual(len(css), 9)

    def test_unbounded_proof_and_bounded_proof_are_not_the_same_badge(self):
        page = self.render(
            document_with([finding_for("proven_under_assumptions"), finding_for("proven_bounded")])
        )
        self.assertIn("PROVEN (bounded)", page)
        self.assertIn("BOUNDED: only up to 8 cycle(s)", page)
        self.assertIn("unbounded claim", page)

    def test_bounded_counterexample_shows_the_cycle_it_was_found_at(self):
        page = self.render(document_with([finding_for("bounded_counterexample")]))
        self.assertIn("witness found at cycle bound 5", page)
        self.assertIn("BOUNDED: only up to 12 cycle(s)", page)

    def test_inconclusive_results_stay_visible(self):
        page = self.render(
            document_with(
                [finding_for("unknown"), finding_for("timeout"), finding_for("error")]
            )
        )
        self.assertIn("no verdict was reached", page)
        self.assertIn("a resource limit was reached", page)
        self.assertIn("the plugin returned None", page)
        self.assertIn("timeout_s: 60", page)

    def test_unsupported_primitives_are_listed(self):
        page = self.render(document_with([finding_for("unsupported")]))
        self.assertIn("Not covered by this analysis", page)
        self.assertIn("RAMB18E1", page)
        self.assertIn("coverage gap", page)
        self.assertIn("mem_inst/bram_0", page)

    def test_unrecognized_status_is_flagged_not_hidden(self):
        finding = finding_for("heuristic")
        finding["status"] = "totally_new_status"
        page = self.render(document_with([finding]))
        self.assertIn("UNRECOGNIZED STATUS", page)
        self.assertIn("totally_new_status", page)

    def test_findings_are_ordered_worst_first(self):
        page = self.render(
            document_with(
                [
                    finding_for("proven_under_assumptions"),
                    finding_for("heuristic"),
                    finding_for("counterexample"),
                ]
            )
        )
        positions = [
            page.index("finding with status counterexample"),
            page.index("finding with status heuristic"),
            page.index("finding with status proven_under_assumptions"),
        ]
        self.assertEqual(positions, sorted(positions))

    def test_assumptions_are_shown_with_their_discharge_state(self):
        page = self.render(document_with([finding_for("proven_under_assumptions")]))
        self.assertIn("single clock domain", page)
        self.assertIn("assumed, not checked", page)

    def test_empty_assumption_list_says_so(self):
        page = self.render(document_with([finding_for("proven_bounded")]))
        self.assertIn("this claim is stated to rest on nothing", page)

    def test_shipped_examples_cover_all_nine_statuses(self):
        if not os.path.isdir(EXAMPLES_DIR):
            self.skipTest("hal_findings examples are not in this checkout")
        paths = sorted(
            os.path.join(EXAMPLES_DIR, name)
            for name in os.listdir(EXAMPLES_DIR)
            if name.endswith(".json")
        )
        loaded = report.load_documents(paths)
        options = report.ReportOptions(os.path.join(self.tmp, "examples.html"))
        page, builder = report.build_report(loaded, options)
        for document in loaded:
            self.assertEqual(document.validation_errors, [], document.path)
        seen = {
            finding["status"] for document in loaded for finding in document.findings
        }
        self.assertEqual(seen, set(self.ALL))
        for status in self.ALL:
            self.assertIn(report.STATUS_META[status]["label"], page)


