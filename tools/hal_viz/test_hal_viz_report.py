"""Standalone unit tests for ``hal_viz report``.

The report generator is pure standard library and needs neither a built HAL nor
Graphviz, so everything below runs on any machine:

    python tools/hal_viz/test_hal_viz_report.py
    # or
    python -m unittest discover -s tools/hal_viz -t tools -p "test_*.py"

What is covered is what the report is trusted for: that untrusted, netlist
derived strings can never break out of the HTML, that all nine findings
statuses render and stay distinguishable, that a missing artifact, a truncated
list, a bounded claim, a coverage gap and an unknown result are all visible
markers rather than silence, and that the page opens offline (no external
request, no script).
"""

