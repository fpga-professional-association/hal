class TestCli(ReportTestCase):
    def _run(self, argv):
        return cli.main(argv)

    def test_report_subcommand_writes_a_page(self):
        path = self.write_document(
            document_with([finding_for(status) for status in TestStatuses.ALL])
        )
        out = os.path.join(self.tmp, "out", "report.html")
        self.assertEqual(self._run(["report", path, "-o", out, "-q"]), 0)
        self.assertTrue(os.path.isfile(out))
        with open(out, encoding="utf-8") as handle:
            page = handle.read()
        self.assertIn("<!doctype html>", page)
        self.assertIn("HAL findings report", page)

    def test_output_directory_gets_a_default_name(self):
        path = self.write_document(document_with([finding_for("heuristic")]))
        out_dir = os.path.join(self.tmp, "out") + os.sep
        self.assertEqual(self._run(["report", path, "-o", out_dir, "-q"]), 0)
        self.assertTrue(os.path.isfile(os.path.join(self.tmp, "out", "findings_report.html")))

    def test_extension_is_added_when_missing(self):
        self.assertTrue(
            cli._resolve_report_output(os.path.join(self.tmp, "r")).endswith("r.html")
        )
        self.assertTrue(
            cli._resolve_report_output(os.path.join(self.tmp, "r.htm")).endswith("r.htm")
        )

    def test_multiple_documents_are_merged_into_one_page(self):
        first = self.write_document(document_with([finding_for("heuristic")]), "a.json")
        second = self.write_document(document_with([finding_for("error")]), "b.json")
        out = os.path.join(self.tmp, "both.html")
        self.assertEqual(self._run(["report", first, second, "-o", out, "-q"]), 0)
        with open(out, encoding="utf-8") as handle:
            page = handle.read()
        self.assertIn("a.json", page)
        self.assertIn("b.json", page)
        self.assertIn("2 document(s)", page)

    def test_strict_fails_on_an_invalid_document_but_still_writes_it(self):
        document = document_with([finding_for("heuristic")])
        document["findings"][0]["bounds"] = {"unbounded": True}
        path = self.write_document(document, "invalid.json")
        out = os.path.join(self.tmp, "strict.html")
        code = self._run(["report", path, "-o", out, "--strict", "-q"])
        self.assertTrue(os.path.isfile(out))
        loaded = report.load_document(path)
        self.assertEqual(code, 1 if loaded.validation_errors else 0)

    def test_missing_document_exits_one_with_a_message(self):
        code = self._run(
            ["report", os.path.join(self.tmp, "gone.json"), "-o", os.path.join(self.tmp, "x.html")]
        )
        self.assertEqual(code, 1)

    def test_report_needs_no_hal(self):
        # The subcommand must not take --hal-lib: it never imports hal_py.
        parser = cli.build_parser()
        args = parser.parse_args(["report", "doc.json"])
        self.assertFalse(hasattr(args, "hal_lib"))
        self.assertTrue(callable(args.func))


