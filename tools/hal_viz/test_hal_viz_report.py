class TestOffline(ReportTestCase):
    def test_page_makes_no_external_request(self):
        svg_path = os.path.join(self.tmp, "scoped.svg")
        with open(svg_path, "w", encoding="utf-8") as handle:
            handle.write(SVG_WITH_ACTIVE_CONTENT)
        finding = finding_for("counterexample", id="test/with-evidence")
        finding["evidence"] = [{"kind": "file", "path": "scoped.svg"}]
        page = self.render(
            document_with([finding] + [finding_for(s) for s in TestStatuses.ALL]),
            artifacts=[svg_path],
        )
        lowered = page.lower()
        # XML namespace URIs are identifiers, not fetches; everything else that
        # looks like a URL would be an external request and must not be there.
        without_namespaces = re.sub(r'xmlns(:\w+)?="[^"]*"', "", lowered)
        self.assertNotIn("<script", lowered)
        self.assertNotIn("http://", without_namespaces)
        self.assertNotIn("https://", without_namespaces)
        self.assertNotIn("<link ", lowered)
        self.assertNotIn('src="//', lowered)
        self.assertNotIn("@import", lowered)
        # styles are inline, so exactly one <style> block and no stylesheet link
        self.assertEqual(lowered.count("<style>"), 1)

    def test_page_is_well_formed_enough_to_parse(self):
        from html.parser import HTMLParser

        class Parser(HTMLParser):
            def __init__(self):
                HTMLParser.__init__(self)
                self.tags = []

            def handle_starttag(self, tag, attrs):
                self.tags.append(tag)

        page = self.render(document_with([finding_for(s) for s in TestStatuses.ALL]))
        parser = Parser()
        parser.feed(page)
        self.assertIn("section", parser.tags)
        self.assertIn("table", parser.tags)
        self.assertNotIn("script", parser.tags)


class TestPaths(unittest.TestCase):
    def test_relative_href_is_url_quoted_and_uses_forward_slashes(self):
        base = os.path.abspath(os.path.join("a", "b"))
        target = os.path.join(base, "c d", "e#f.svg")
        href = report.relative_href(target, base)
        self.assertEqual(href, "c%20d/e%23f.svg")

    def test_relative_href_can_walk_up(self):
        base = os.path.abspath(os.path.join("a", "b"))
        target = os.path.abspath(os.path.join("a", "x.svg"))
        self.assertEqual(report.relative_href(target, base), "../x.svg")

    def test_resolve_path_honours_absolute_evidence_paths(self):
        absolute = os.path.abspath(os.path.join(os.sep, "tmp", "x.vcd"))
        self.assertEqual(report.resolve_path(absolute, "/elsewhere"), os.path.normpath(absolute))
        self.assertEqual(
            report.resolve_path("x.vcd", os.path.join("a", "b")),
            os.path.normpath(os.path.join("a", "b", "x.vcd")),
        )


