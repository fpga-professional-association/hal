"""Unit tests for the clock-step page generator. No HAL, no browser, no Graphviz.

Run from the repository root::

    python -m unittest discover -s tools/hal_viz -t tools -p "test_*.py"

The generator's whole job is a join between two committed artifacts, so what
these tests assert is the join: which drawn node and which drawn arrow ends up
carrying which net's value, what happens to the ones that cannot be resolved,
and that the emitted document really is one self-contained file.
"""

